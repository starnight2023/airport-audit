# =============================================================================
# evaluation/ — 生成式部分自动化评测模块
# =============================================================================
# 定位：
#   对"LLM 生成的稽核报告"做可重复、可量化、尽量确定性的评测。
#   确定性规则引擎输出视为 authoritative ground truth，LLM 报告只被评判。
#
# 设计原则（详见 README / config.yaml）：
#   1. Ground Truth 全部由规则引擎 / 账单 / 合同自动构建，不人工标注；
#   2. Claim 抽取确定性优先，仅自由文本数字走正则，不默认调 LLM；
#   3. Citation Truthfulness 退化为集合比对（clause_id 存在性 + 规则引擎使用性）；
#   4. LLM Judge 仅作为可选第二层（默认关闭），严格 JSON + 重试 + judge_error 兜底；
#   5. 报告生成走 audit_mock + report_node，不调用与评测无关的 Planner LLM。
#
# 入口：
#   python -m evaluation.runner [--cases 20] [--merchant M001] [--month 2025-01]
